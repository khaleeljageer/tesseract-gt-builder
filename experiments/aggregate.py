"""Collect variant results into LaTeX tables and the scaling figure.

Writes straight into paper/ so the manuscript picks up new numbers on the
next compile. Nothing here invents a value: a variant with no result.json
simply does not appear, and every cell traces to one file on disk.
"""

import argparse
import json
import sys
from pathlib import Path

RESULTS = Path("results")
PAPER = Path("../paper")


def load(experiment):
    """Every result.json under results/<experiment>/, newest wins."""
    out = []
    for path in sorted((RESULTS / experiment).glob("*/result.json")):
        out.append(json.loads(path.read_text(encoding="utf-8")))
    return out


def pct(x):
    return f"{x * 100:.2f}"


def ci_str(m):
    ci = m.get("cer_grapheme_ci95")
    if not ci:
        return "--"
    return f"[{ci[0] * 100:.2f}, {ci[1] * 100:.2f}]"


def table_fonts(rows):
    if not rows:
        return None
    rows = sorted(rows, key=lambda r: r["manifest"]["n_fonts"])
    n_lines = rows[0]["variant"]["n_lines"]
    body = "\n".join(
        f"{r['manifest']['n_fonts']:>2} & {pct(r['metrics']['cer_grapheme_micro'])} & "
        f"{ci_str(r['metrics'])} & {pct(r['metrics']['cer_codepoint_micro'])} & "
        f"{pct(r['metrics']['wer_micro'])} \\\\"
        for r in rows)
    return f"""% generated by experiments/aggregate.py -- do not edit
\\begin{{table}}[t]
\\centering\\small
\\begin{{tabular}}{{rcccc}}
\\toprule
Fonts & Graph.\\ CER $\\downarrow$ & 95\\% CI & CP CER $\\downarrow$ & WER $\\downarrow$ \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\caption{{Typographic diversity ablation. Training corpus held fixed at
{n_lines:,} lines; only the number of typefaces varies. All rows evaluated on
the same held-out real-document test set.}}
\\label{{tab:ablation-fonts}}
\\end{{table}}
"""


def table_size(rows):
    if not rows:
        return None
    rows = sorted(rows, key=lambda r: r["variant"]["n_lines"])
    body = "\n".join(
        f"{r['variant']['n_lines']:,} & {pct(r['metrics']['cer_grapheme_micro'])} & "
        f"{ci_str(r['metrics'])} & {pct(r['metrics']['wer_micro'])} \\\\"
        for r in rows)
    return f"""% generated by experiments/aggregate.py -- do not edit
\\begin{{table}}[t]
\\centering\\small
\\begin{{tabular}}{{rccc}}
\\toprule
Lines & Graph.\\ CER $\\downarrow$ & 95\\% CI & WER $\\downarrow$ \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\caption{{Corpus scale ablation, all 27 typefaces.}}
\\label{{tab:ablation-size}}
\\end{{table}}
"""


def table_domain(rows):
    if not rows:
        return None
    order = {"literary": 0, "newsprint": 1, "mixed": 2}
    rows = sorted(rows, key=lambda r: order.get(r["variant"]["name"], 9))
    body = "\n".join(
        f"{r['variant']['name'].capitalize()} & "
        f"{pct(r['metrics']['cer_grapheme_micro'])} & {ci_str(r['metrics'])} & "
        f"{pct(r['metrics']['wer_micro'])} \\\\"
        for r in rows)
    n = rows[0]["variant"]["n_lines"]
    return f"""% generated by experiments/aggregate.py -- do not edit
\\begin{{table}}[t]
\\centering\\small
\\begin{{tabular}}{{lccc}}
\\toprule
Training register & Graph.\\ CER $\\downarrow$ & 95\\% CI & WER $\\downarrow$ \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\caption{{Register ablation. Each arm trained on {n:,} lines -- the size of
the smaller (newsprint) arm -- so the comparison reflects register rather
than corpus volume.}}
\\label{{tab:ablation-domain}}
\\end{{table}}
"""


def figure_scaling(rows, out_path):
    """CER against corpus size, log-x. Vector PDF, colourblind-safe."""
    if len(rows) < 2:
        print("[skip] scaling figure needs at least 2 size variants")
        return
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("[skip] matplotlib unavailable")
        return

    rows = sorted(rows, key=lambda r: r["variant"]["n_lines"])
    x = [r["variant"]["n_lines"] for r in rows]
    y = [r["metrics"]["cer_grapheme_micro"] * 100 for r in rows]
    lo = [r["metrics"].get("cer_grapheme_ci95", [None, None])[0] for r in rows]
    hi = [r["metrics"].get("cer_grapheme_ci95", [None, None])[1] for r in rows]

    fig, ax = plt.subplots(figsize=(3.5, 2.5))
    if all(v is not None for v in lo):
        ax.fill_between(x, [v * 100 for v in lo], [v * 100 for v in hi],
                        color="#0072B2", alpha=0.15, linewidth=0)
    ax.plot(x, y, marker="o", color="#0072B2", linewidth=1.6, markersize=4)
    ax.set_xscale("log")
    ax.set_xlabel("Training lines")
    ax.set_ylabel("Grapheme CER (\\%)" if plt.rcParams["text.usetex"]
                  else "Grapheme CER (%)")
    ax.grid(alpha=0.25, linewidth=0.5)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, bbox_inches="tight")
    print(f"wrote {out_path}")


def confusion_table(rows, top=12):
    """Top grapheme confusions from the largest-corpus variant."""
    if not rows:
        return None
    best = max(rows, key=lambda r: r["variant"]["n_lines"])
    subs = best["metrics"].get("top_substitutions", [])[:top]
    if not subs:
        return None
    total = sum(s["count"] for s in best["metrics"].get("top_substitutions", []))
    body = "\n".join(
        f"\\ta{{{s['ref']}}} & \\ta{{{s['hyp']}}} & {s['count']} & "
        f"{s['count'] / total * 100:.1f} \\\\"
        for s in subs)
    return f"""% generated by experiments/aggregate.py -- do not edit
\\begin{{table}}[t]
\\centering\\small
\\begin{{tabular}}{{llrr}}
\\toprule
Reference & Recognised & Count & \\% of subs. \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\caption{{Most frequent grapheme substitutions, {best['variant']['name']}
variant. Percentages are of all substitution errors.}}
\\label{{tab:confusions}}
\\end{{table}}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(PAPER), help="paper directory")
    args = ap.parse_args()
    out = Path(args.out)
    (out / "tables").mkdir(parents=True, exist_ok=True)

    fonts, size, domain = load("fonts"), load("size"), load("domain")
    print(f"loaded  fonts={len(fonts)}  size={len(size)}  domain={len(domain)}")

    if not (fonts or size or domain):
        print("\nNo results yet. Run experiments/run_ablation.py first.")
        return 1

    for name, tex in (("ablation_fonts", table_fonts(fonts)),
                      ("ablation_size", table_size(size)),
                      ("ablation_domain", table_domain(domain)),
                      ("confusions", confusion_table(size or fonts))):
        if tex:
            path = out / "tables" / f"{name}.tex"
            path.write_text(tex, encoding="utf-8")
            print(f"wrote {path}")

    figure_scaling(size, out / "figures" / "scaling.pdf")

    print("\nIn main.tex, replace the placeholder tables with:")
    print("  \\input{tables/ablation_fonts}")
    print("  \\input{tables/ablation_size}")
    print("  \\input{tables/ablation_domain}")
    print("  \\input{tables/confusions}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
